  function trialChoice(t, key, c) {
    var sk = c.attorney ? c.attorney.skill : 20, ev = c.evidence.strength;
    var delta = 0;
    if (key.indexOf('vs:') === 0) {
      if (key === 'vs:peremptory') { if (t.peremptory <= 0) { notice('No challenges left', 'You have used all peremptory challenges.'); return SCREEN.trial(); }
        t.peremptory--; t.jury.favour += ri(2, 10); delta = 2; }
      else if (key === 'vs:forcause') { if (pct(.35 + sk/400)) { t.jury.favour += ri(4,12); dev(c, 'A juror was excused for cause.'); } else notice('Challenge denied', 'The juror stayed.'); }
      else if (key === 'vs:compose') { t.jury.favour += ri(1,7); t.jury.biases.push(pick(['law-and-order','sceptical of police','sympathetic to defendants','impatient'])); }
      else delta = 0;
    } else if (key.indexOf('op:') === 0) {
      delta = key === 'op:doubt' ? ri(4,9) : key === 'op:story' ? ri(2,7) : key === 'op:investigation' ? ri(3,8) - ev/30 : ri(0,3);
    } else if (key.indexOf('pc:') === 0) {
      delta = key === 'pc:aggressive' ? ri(5,13) - ev/22 : key === 'pc:impeach' ? ri(6,14) - ev/30 :
        key === 'pc:forensic' ? ri(4,12) + c.evidence.experts.length*4 : -ri(2,7);
      if (key === 'pc:impeach' && c.evidence.motions.indexOf('suppress') >= 0) delta += 5;
    } else if (key.indexOf('dc:') === 0) {
      delta = key === 'dc:testify' ? ri(-4,12) + sk/12 : key === 'dc:witness' ? ri(4,10) + c.evidence.witnesses.length*3 + c.evidence.experts.length*4 :
        key === 'dc:rest' ? ri(-2,3) : ri(2,7);
      if (key === 'dc:testify' && c.evidence.alibi) delta += 6;
    } else if (key.indexOf('cl:') === 0) {
      delta = key === 'cl:burden' ? ri(4,10) : key === 'cl:elements' ? ri(3,9) + sk/20 :
        key === 'cl:fairness' ? ri(1,6) : ri(2,8) + c.evidence.suppressed*3;
    } else if (key === '__verdict') { t.step = 6; return verdictScreen(); }
    delta += (t.jury.favour - 50) / 12 + (t.mode === 'bench' ? c.judge.lean / 8 : 0);
    t.score = clampN(t.score + delta, 0, 100);
    t.done.push(key);
    t.step = Math.min(t.step + 1, 5);
    dev(c, 'Trial step "' + key + '": defence position now ' + Math.round(t.score) + '%.');
    SCREEN.trial();
  }
  function verdictScreen() {
    var c = C(), t = c.trial;
    var convictP = clampN((c.evidence.strength / 100) * .62 + (100 - t.score) / 100 * .42 + (c.rejectedPlea ? .05 : 0) - (c.attorney ? c.attorney.skill : 20)/600, .04, .94);
    var roll = Math.random();
    var result, reason;
    if (roll < convictP * .12) { result = 'hung'; reason = 'The jury could not agree. The judge declared a mistrial.'; }
    else if (roll < convictP * .20 && c.exposure.tier !== 'MISD') { result = 'lesser'; reason = 'Guilty of a lesser included offence.'; }
    else if (roll < convictP) { result = 'guilty'; reason = 'Guilty as charged.'; }
    else { result = 'not_guilty'; reason = 'Not guilty.'; }
    if (G.mods && G.mods.alwaysWinCourt) { result = 'not_guilty'; reason = 'Not guilty (court-house mod).'; }
    c.verdict = { result:result, reason:reason, convictP:Math.round(convictP*100) };
    stamp();
    var h = '<div class="mf-wrap">' + lead('<b>The ' + (t.mode === 'bench' ? 'judge' : 'jury') + ' returns: ' + esc(reason) + '</b>') +
      card('<b>Charge:</b> ' + esc(c.charge) + '<br><b>Statute:</b> ' + esc(c.statute) +
        '<br><b>Conviction probability entering deliberation:</b> ' + c.verdict.convictP + '%' +
        '<br><b>Defence position:</b> ' + Math.round(t.score) + '%') +
      sec('What happens next') +
      (result === 'not_guilty' ? btn('__finish','Walk out of the courtroom') :
        result === 'hung' ? btn('__retrial','Accept a retrial') + btn('__finish_p','Accept a plea to avoid retrial') :
        result === 'lesser' ? btn('__sentence','Proceed to sentencing on the lesser offence') :
        btn('__sentence','Proceed to sentencing')) + '</div>';
    show('VERDICT', h, hub, {
      __sentence: function () { if (result === 'lesser') { c.exposure.max = Math.max(6, Math.round((c.exposure.max === 'LIFE' ? 240 : c.exposure.max) * .45)); c.charge += ' (lesser included)'; }
        logCase(c, 'Verdict: ' + reason); say('The verdict came back: ' + reason); next('verdict'); },
      '__retrial': function () { c.trial = null; c.evidence.strength -= ri(3, 8); logCase(c, 'Mistrial declared; retrial ordered.'); dev(c, 'Hung jury. A retrial was set.'); notice('Mistrial', 'The case will be tried again.'); go('trial'); },
      '__finish_p': function () { c.pleaTaken = { type:'plea', label:'post-mistrial plea', discount:.6 }; logCase(c, 'Entered a plea after the hung jury.'); next('verdict'); },
      __finish: function () { finish('acquitted'); }
    });
  }

  function exposure(k, key, crime, valueUSD) {
    var S = D.states[k], off = D.offenses[key], tier = off.tier;
    /* Real theft threshold decides misdemeanor vs felony. */
    if (PROPERTY.indexOf(String(crime).toLowerCase()) >= 0 && S.theftThreshold) {
      var v = valueUSD == null ? ri(40, 4200) : valueUSD;
      tier = (v >= S.theftThreshold) ? 'FELONY_LOW' : 'MISD';
      key = tier === 'MISD' ? 'petty_theft' : 'grand_theft';
      off = D.offenses[key];
      return {
        key: key, tier: tier, label: tier === 'MISD' ? 'Petty theft (under ' + usd(S.theftThreshold) + ')' : 'Grand theft (' + usd(S.theftThreshold) + '+ felony threshold met)',
        cls: classLabel(k, tier), min: tier === 'MISD' ? 0 : 0,
        max: tier === 'MISD' ? 6 : 36, fine: tier === 'MISD' ? 1000 : 10000,
        statute: S.sources.split(',')[0].trim(), source: 'verified-threshold',
        note: 'Real ' + S.name + ' theft felony threshold: ' + usd(S.theftThreshold) + '. Stolen property valued at ' + usd(v) + '.',
        thresholdUsed: true
      };
    }
    if (key === 'dui') {
      var days = S.duiMaxDays || 180;
      return {
        key: key, tier: 'MISD', label: off.label, cls: classLabel(k, 'MISD'),
        min: 0, max: Math.max(1, Math.round(days / 30.44)), fine: 1500,
        statute: S.sources.split(',').slice(-1)[0].trim(), source: 'verified',
        note: 'Verified ' + S.name + ' first-offence DUI maximum: ' + S.duiNote + ' (' + days + ' days). Administrative licence suspension is separate.'
      };
    }
    if (k === 'CA' && D.caMatrix[key]) {
      var m = D.caMatrix[key];
      return { key:key, tier:tier, label:off.label, cls:m[0], min:m[1], max:m[2], fine:m[3],
        statute:m[4], source:'verified', note:'Audited California statutory range.' };
    }
    var cr = D.classRanges[k];
    if (cr && TIER_CLASS[k] && cr[TIER_CLASS[k][tier]]) {
      var r = cr[TIER_CLASS[k][tier]];
      return { key:key, tier:tier, label:off.label, cls:classLabel(k, tier), min:r[0], max:r[1], fine:r[2],
        statute:r[3], source:'verified-class',
        note:'Real ' + S.name + ' statutory range for ' + classLabel(k, tier) + '; the offence-to-class mapping is modeled.' };
    }
    var mm = MODEL[tier];
    return { key:key, tier:tier, label:off.label, cls:classLabel(k, tier), min:mm[0], max:mm[1], fine:mm[2],
      statute:S.sources.split(',')[0].trim(), source:'modeled',
      note:'Modeled statutory exposure from ' + S.name + "'s real " + S.classification + ' classification. Not a verified statute for this specific offence.' };
  }

  /* --------------------------------------------------------------- case data */
  function freshState() { return { record: [], history: [], courtGang: null, active: null, cases: 0 }; }
  function CS() {
    if (!state.court || typeof state.court !== 'object') state.court = freshState();
    if (!Array.isArray(state.court.record)) state.court.record = [];
    if (!Array.isArray(state.court.history)) state.court.history = [];
    return state.court;
  }
  function priors() { return CS().record.filter(function (r) { return r.result === 'convicted'; }).length; }
  function gangAffiliation() {
    var g = CS().courtGang;
    if (g && g.name) return g;
    try {
      var P = window.PRISON_LIFE && window.PRISON_LIFE.S && window.PRISON_LIFE.S();
      if (P && P.gang && P.gang.name) return { name: P.gang.name, proven: true, source: 'prison' };
    } catch (e) {}
    try { if (state.prison && state.prison.gang && state.prison.gang.name) return { name: state.prison.gang.name, proven: true, source: 'prison' }; } catch (e) {}
    try { if (state.gang && state.gang.name) return { name: state.gang.name, proven: true, source: 'street' }; } catch (e) {}
    return null;
  }

  function begin(e) {
    var cs = CS();
    if (cs.active && cs.active.crime === e.crime && cs.active.open) { COURT.hub(); return; }
    var k = (state.usState && D.states[state.usState]) ? state.usState : (U.stateOfCity(state.city) || 'CA');
    var crime = e.crime;
    var key = offenceKey(crime);
    var valueUSD = PROPERTY.indexOf(String(crime).toLowerCase()) >= 0 ? ri(40, 4200) : null;
    var ex = exposure(k, key, crime, valueUSD);
    var S = D.states[k];
    var juv = state.age < 18;
    var dp = !!e.dp;
    var deathOK = DEATH_AUTHORIZED.indexOf(k) >= 0;
    var capitalNote = null;
    if (dp && !deathOK) {
      capitalNote = 'Capital punishment is not authorised in ' + S.name + '; the maximum exposure is life without parole. The death notice was struck.';
      dp = false;
    }
    var c = {
      id: 'C' + Date.now() + '-' + ri(100, 999), open: true,
      stateCode: k, stateName: S.name, city: state.city || S.capital,
      county: (state.city || S.capital) + ' County',
      courtName: (juv ? 'Juvenile and Family' : 'Superior / District') + ' Court of ' + S.name,
      crime: crime, offenceKey: key, charge: ex.label, cls: ex.cls, statute: ex.statute,
      exposure: { min: ex.min, max: ex.max, fine: ex.fine, tier: ex.tier },
      exposureSource: ex.source, exposureNote: ex.note,
      statuteList: S.sources, classification: S.classification,
      theftThreshold: S.theftThreshold, duiMaxDays: S.duiMaxDays,
      gang: { type: S.gang.type, statute: S.gang.statute, maxMonths: S.gang.maxMonths, note: S.gang.note,
        filed: false, proven: false, dismissed: false, proof: null, affiliation: null },
      bail: { system: S.bail.system, note: S.bail.note, amount: 0, posted: false, method: null, detained: true, conditions: [] },
      guidelines: S.guidelines, threeStrikes: S.threeStrikes,
      juv: juv, juvWaived: false,
      dp: dp, dpKind: e.dpKind || null, capitalNote: capitalNote,
      lean: Number(e.lean) || 0,
      lo: e.lo || 1, hi: e.hi || 4,
      fugitive: state.fugitive ? { left: state.fugitive.left, crime: state.fugitive.crime, death: !!state.fugitive.death } : null,
      valueUSD: valueUSD, thresholdUsed: !!ex.thresholdUsed,
      stage: 'booking', done: {}, stageIndex: 0,
      attorney: null, judge: null, prosecutor: null,
      evidence: { strength: ri(38, 72), suppressed: 0, motions: [], experts: [], witnesses: [], alibi: false },
      pleaOffer: null, pleaTaken: null,
      trial: null, verdict: null, sentence: null,
      appeal: null, probation: null, recordFiled: false,
      fired: [], log: [], developments: [],
      firedEvents: [],
      moneySpent: 0, goodwill: 0,
      enhancements: [], mitigations: [],
      famous: !!(state.art && state.art.fameOn),
      political: !!(window.POLITICS && window.POLITICS.S && window.POLITICS.S().office)
    };
    /* judge / prosecutor */
    c.judge = { name: 'Hon. ' + person(), temperament: pick(['by-the-book','lenient','hard-nosed','unpredictable','scholarly']), lean: ri(-12, 12) };
    c.prosecutor = { name: 'ADA ' + person(), aggression: ri(35, 85) };
    /* bail amount, from real system */
    var base = c.exposure.max === 'LIFE' ? 250000 : Math.max(500, Math.round(c.exposure.max * 900));
    c.bail.amount = c.bail.system === 'no_cash' || c.bail.system === 'risk' ? 0 : Math.min(1000000, base);
    /* possible gang filing */
    var aff = gangAffiliation();
    c.gang.affiliation = aff ? aff.name : null;
    c.gang.filed = !!(aff && S.gang.type === 'standalone' && c.exposure.tier !== 'MISD' && pct(0.62));
    c.gang.filedConditional = !!(aff && S.gang.type === 'conditional' && c.exposure.tier !== 'MISD' && pct(0.40));
    cs.active = c;
    cs.cases = (cs.cases || 0) + 1;
    logCase(c, 'Arrested in ' + c.city + ', ' + k + '. Charged under ' + S.name + ' law.');
    logCase(c, 'Charge: ' + c.charge + ' (' + c.cls + ') · ' + c.statute);
    if (capitalNote) logCase(c, capitalNote);
    if (c.gang.filed) logCase(c, 'Prosecution filed a gang enhancement: ' + S.gang.statute);
    say('I was arrested in ' + c.city + ', ' + k + ', and charged under ' + S.name + ' law with ' + c.charge + '.');
    if (c.gang.filed) say('The prosecutor also filed a gang enhancement under ' + S.gang.statute + '.');
    COURT.go('booking');
  }


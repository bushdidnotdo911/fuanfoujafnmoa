  function gangProof() {
    var c = C(), S = D.states[c.stateCode], g = c.gang;
    if (!g.filed || g.proven || g.dismissed) return gangScreen();
    var isCA = c.stateCode === 'CA';
    var els = isCA ? [
      { k:'benefit', t:'Benefit / direction / association', d:'The offence was committed for the benefit of, at the direction of, or in association with a criminal street gang, with specific intent to promote, further or assist.' },
      { k:'pattern', t:'Predicate pattern (substantial evidence)', d:'AB 333 requires substantial evidence of a pattern of criminal gang activity — real predicate offences, not just expert testimony naming old cases.' },
      { k:'existence', t:'Gang existence & primary activities', d:'The group is an ongoing organisation with a common name/sign and identified primary activities.' },
      { k:'nexus', t:'Nexus to this charge', d:'A concrete connection between this case and the gang\'s criminal purpose.' }
    ] : [
      { k:'benefit', t:'Gang-related purpose', d:'The offence was committed in association with or for the benefit of a criminal street gang.' },
      { k:'pattern', t:'Pattern of gang activity', d:'Proof of qualifying predicate offences.' },
      { k:'existence', t:'Ongoing organisation', d:'The group is a continuing criminal street gang.' },
      { k:'nexus', t:'Attachment to this offence', d:'The statute attaches an enhancement to this class of offence.' }
    ];
    if (!g.proof) {
      g.proof = {};
      els.forEach(function (e) { e.v = ri(30, 88); g.proof[e.k] = { v: e.v, challenged: false }; });
    } else {
      els.forEach(function (e) { e.v = g.proof[e.k].v; e.challenged = g.proof[e.k].challenged; });
    }
    var h = '<div class="mf-wrap">' + lead('<b>Gang proof hearing · ' + esc(S.name) + '</b><br>' +
      (isCA ? 'Under PC 186.22 as amended by <b>AB 333 (2022)</b>, every element must be established by substantial evidence. Membership, tattoos or a nickname are not enough.' :
        'Under ' + esc(S.gang.statute) + ', the prosecution must establish each element before an added term is imposed.')) +
      sec('Prosecution evidence by element') +
      els.map(function (e) { return '<div class="mf-card"><div class="mf-lead"><b>' + esc(e.t) + '</b>' + (e.challenged ? ' <span class="ct-badge ct-verified">CHALLENGED</span>' : '') + '<br>' + esc(e.d) + '</div>' + bar('Evidence', e.v, e.v < 50 ? 'low' : '') + '</div>'; }).join('') +
      sec('Your challenge') +
      btn('ch:pattern','Challenge the predicate pattern','') +
      btn('ch:benefit','Challenge gang purpose / specific intent','') +
      btn('ch:nexus','Challenge attachment to this charge','') +
      btn('ch:existence','Challenge the gang\'s existence','') +
      btn('__rule','Submit to the court\'s ruling') +
      '<div class="mf-sub">Each challenge can reduce the prosecution\'s evidence on that element. If any element falls below the proof threshold, the enhancement is struck.</div></div>';
    var handlers = {};
    ['pattern','benefit','nexus','existence'].forEach(function (k) {
      handlers['ch:' + k] = function () {
        var p = g.proof[k];
        if (p.challenged) { notice('Already challenged', 'You have already challenged that element.'); return gangProof(); }
        p.challenged = true;
        var cut = ri(14, 34) + Math.round((c.attorney ? c.attorney.skill : 25) / 6);
        p.v = clampN(p.v - cut, 0, 100);
        dev(c, 'Defence challenged the "' + k + '" element of the gang enhancement; evidence fell to ' + p.v + '%.');
        logCase(c, 'Gang proof hearing: ' + k + ' challenged (-' + cut + ').');
        notice('Challenge sustained in part', 'The court allowed argument on ' + k + '. Evidence now ' + p.v + '%.');
        gangProof();
      };
    });
    handlers.__rule = function () {
      var failed = Object.keys(g.proof).filter(function (k) { return g.proof[k].v < 50; });
      if (failed.length) {
        g.dismissed = true;
        dev(c, 'Gang enhancement STRUCK: insufficient evidence on ' + failed.join(', ') + '.');
        logCase(c, 'The court struck the gang enhancement under ' + S.gang.statute + ' (AB 333 / proof standard not met).');
        say('The judge struck the gang enhancement. The prosecution had not proved the pattern.');
        notice('Enhancement struck', 'Under ' + S.name + ' law the gang enhancement was dismissed for insufficient proof.');
      } else {
        g.proven = true;
        dev(c, 'Gang enhancement PROVEN under ' + S.gang.statute + ': +' + yrs(S.gang.maxMonths || 0) + '.');
        logCase(c, 'Gang enhancement proven under ' + S.gang.statute + '.');
        say('The judge found the gang enhancement proven under ' + S.gang.statute + '.');
        notice('Enhancement proven', 'The added term of ' + yrs(S.gang.maxMonths || 0) + ' will be considered at sentencing.');
      }
      COURT.go(c.stage);
    };
    show('GANG PROOF HEARING', h, function () { COURT.go(c.stage); }, handlers);
  }


  function next(stage) {
    var c = C(); c.done[stage] = true;
    var i = STAGES.indexOf(stage);
    var nx = STAGES[Math.min(i + 1, STAGES.length - 1)];
    /* Plea accepted skips trial and verdict. */
    if (stage === 'plea' && c.pleaTaken && c.pleaTaken.type !== 'trial') nx = 'sentencing';
    if (stage === 'verdict' && c.verdict && c.verdict.result !== 'guilty') nx = 'record';
    if (stage === 'sentencing' && !c.sentence) nx = 'record';
    if (stage === 'preliminary' && c.prelimDismissed) nx = 'record';
    if (stage === 'trial' && c.juvWaived === false && c.juv) { /* juvenile still adjudicates */ }
    go(nx);
  }


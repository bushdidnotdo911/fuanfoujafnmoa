/* ==========================================================================
 * court.js — Free Life Criminal Court (United States edition)
 * --------------------------------------------------------------------------
 * An interactive state-criminal-court system that replaces the game's vanilla
 * "Criminal Charges -> Plea -> Verdict" card chain.
 *
 * Jurisdiction comes from the US-states module: an arrest in Los Angeles is
 * prosecuted under California law; an arrest in Chicago under Illinois law.
 * Real, verified per-jurisdiction fields (classification system, theft felony
 * threshold, first-offence DUI maximum, gang-enhancement statute and term,
 * bail/pretrial system, statutory citations) come from court-data.js.
 * Offence-to-class mappings and numeric ranges that could not be verified for
 * every jurisdiction are generated by an explicitly-labelled statutory-
 * exposure model and are marked "modeled" in the in-game Legal Codex.
 *
 * No eval, no Function, no user JS, no network requests, no SVG/coded art.
 * All icons are generated raster PNGs in court/.
 * ========================================================================== */

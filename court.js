    'pa':     { MISD:'Misdemeanor 1', FELONY_LOW:'Felony 3', FELONY_MID:'Felony 2', FELONY_HIGH:'Felony 1', LIFE:'Felony 1 (life)' },
    'tx':     { MISD:'Class A misdemeanor', FELONY_LOW:'State jail felony', FELONY_MID:'third-degree felony', FELONY_HIGH:'first-degree felony', LIFE:'capital felony' },
    'wa':     { MISD:'gross misdemeanor', FELONY_LOW:'Class C felony', FELONY_MID:'Class B felony', FELONY_HIGH:'Class A felony', LIFE:'Class A felony (life)' },
    'or':     { MISD:'Class A misdemeanor', FELONY_LOW:'Class C felony', FELONY_MID:'Class B felony', FELONY_HIGH:'Class A felony', LIFE:'Class A felony (life)' },
    'ca':     { MISD:'misdemeanor', FELONY_LOW:'wobbler felony', FELONY_MID:'felony (determinate)', FELONY_HIGH:'serious/violent felony', LIFE:'indeterminate life term' },
    'grid':   { MISD:'misdemeanor', FELONY_LOW:'low-severity felony', FELONY_MID:'mid-severity felony', FELONY_HIGH:'high-severity felony', LIFE:'life sentence' },
    'plain':  { MISD:'misdemeanor', FELONY_LOW:'low-degree felony', FELONY_MID:'mid-degree felony', FELONY_HIGH:'high-degree felony', LIFE:'felony punishable by life' }

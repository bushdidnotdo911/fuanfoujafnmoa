  /* -------------------------------------------------------------- finishing */
  function finish(result, prison) {
    var c = C(); if (!c) return hubBack();
    c.open = false;
    var cs = CS();
    if (result === 'acquitted' || result === 'dismissed' || result === 'reversed' || result === 'closed') {
      logCase(c, 'Case closed: ' + result + '.');
      if (result === 'acquitted' || result === 'dismissed') {
        say(result === 'acquitted' ? 'I was found not guilty and walked free.' : 'The charges against me were dismissed.');
        stat('Happiness', 6);
        notice(result === 'acquitted' ? 'Not guilty' : 'Case dismissed', 'You are free to go. The case is closed.');
      }
      /* escaped convict still returns to custody */
      if (c.fugitive) {
        var p = { crime:c.fugitive.crime + ' and escaping prison', years:Math.max(1, c.fugitive.left + ri(2,5)), served:0,
          name:c.city + ' Correctional Facility', sec:'Medium', juv:false, behavior:ri(25,45), respect:ri(4,15),
          gang:null, job:null, recap:true, death:c.fugitive.death ? { age:state.age+ri(2,6), how:'lethal injection' } : null,
          did:{}, courtCase:c.id, stateCode:c.stateCode };
        logCase(c, 'Despite the outcome, the outstanding escaped-convict sentence still applies.');
        notice('Back to prison', 'You still owe time on the earlier sentence.');
        cs.active = null;
        return sendToPrison(p, c);
      }
      cs.active = null;
      try { screen.classList.remove('open'); } catch (e) {}
      return;
    }
    /* conviction */
    prison = prison || c.pendingPrison;
    if (!prison) { cs.active = null; return; }
    cs.active = null;
    sendToPrison(prison, c);
  }
  function sendToPrison(p, c) {
    try {
      if (G.goToPrison) G.goToPrison(p);
      try { if (window.crimeFamily) window.crimeFamily(c.crime, p); } catch (e) {}
      say('The ' + c.stateName + ' court sent me to ' + p.name + '.');
      notice('Sentenced in ' + c.stateName, yrs(p.years*12) + ' · ' + p.sec + ' security. The prison system has taken over.');
    } catch (e) {
      notice('Court', 'Sentence recorded, but the prison handover could not complete.');
    }
    try { screen.classList.remove('open'); } catch (e) {}
  }


  SCREEN.appeal = function () {
    var c = C(), S = D.states[c.stateCode];
    if (!c.sentence || (c.verdict && c.verdict.result === 'not_guilty')) return go('record');
    var grounds = [
      { k:'suppression', t:'Denial of a suppression motion', d:'Argue the trial court wrongly admitted evidence.' },
      { k:'jury', t:'Jury instruction error', d:'A misstatement of the burden or an element.' },
      { k:'sufficiency', t:'Insufficiency of the evidence', d:'No rational trier of fact could convict.' },
      { k:'sentencing', t:'Sentencing error', d:'Enhancement imposed without the required findings.' },
      { k:'counsel', t:'Ineffective assistance of counsel', d:'Sixth Amendment claim.' },
      { k:'gang', t:'Gang enhancement proof (AB 333 / state standard)', d:'The statutory elements were not established.' }
    ];
    var h = '<div class="mf-wrap">' + lead('<b>Appeal · ' + esc(S.name) + '</b>') +
      card('An appeal is not a new trial. The appellate court reviews the record for legal error. Most convictions are affirmed.') +
      sec('Grounds (pick more than one)') + grounds.map(function (g, i) { return btn('ap:' + i, g.t); }).join('') +
      sec('Counsel') + btn('ap:pd','Appointed appellate counsel') + btn('ap:private','Hire appellate counsel') +
      btn('ap:file','File the notice of appeal') + '</div>';
    var handlers = {};
    grounds.forEach(function (g, i) { handlers['ap:' + i] = function () {
      c.appeal = c.appeal || { grounds:[], counsel:null, filed:false };
      if (c.appeal.grounds.indexOf(g.k) < 0) c.appeal.grounds.push(g.k);
      notice('Ground added', g.d); SCREEN.appeal(); }; });
    handlers['ap:pd'] = function () { c.appeal = c.appeal || { grounds:[], counsel:null, filed:false }; c.appeal.counsel = 'appointed'; notice('Appellate counsel', 'Counsel appointed.'); SCREEN.appeal(); };
    handlers['ap:private'] = function () { var f = ri(8000, 45000); if ((state.money||0) < f) { notice('Cannot afford', usd(f) + ' required.'); return; }
      money(-f); c.moneySpent += f; c.appeal = c.appeal || { grounds:[], counsel:null, filed:false }; c.appeal.counsel = 'private';
      c.appeal.skill = ri(65, 92); notice('Appellate counsel', 'Retailed private appellate counsel for ' + usd(f) + '.'); SCREEN.appeal(); };
    handlers['ap:file'] = function () {
      c.appeal = c.appeal || { grounds:[], counsel:null, filed:false };
      c.appeal.filed = true;
      var sk = c.appeal.skill || (c.appeal.counsel === 'private' ? 75 : 38);
      var merit = clampN(.10 + c.appeal.grounds.length*.055 + sk/700 + (c.gang.dismissed ? .05 : 0), .05, .55);
      var r = Math.random();
      var out = r < merit * .35 ? 'reversed' : r < merit * .65 ? 'modified' : r < merit ? 'remanded' : 'affirmed';
      c.appeal.outcome = out;
      logCase(c, 'Appeal filed (' + c.appeal.grounds.join(', ') + '). Outcome: ' + out + '.');
      dev(c, 'Appellate ruling: ' + out.toUpperCase() + '.');
      if (out === 'reversed') { notice('Reversed', 'Conviction reversed. The case is dismissed.'); CS().record = CS().record.filter(function (x) { return x.caseId !== c.id; }); return finish('reversed'); }
      if (out === 'modified') { var cut = ri(8, 30); c.sentence.months = Math.max(0, (c.sentence.months === 'LIFE' ? 240 : c.sentence.months) - cut);
        dev(c, 'Sentence reduced by ' + yrs(cut) + '.'); notice('Modified', 'Sentence reduced by ' + yrs(cut) + '.');
        c.pendingPrison = buildPrison(c, D.states[c.stateCode], c.sentence); }
      else if (out === 'remanded') { dev(c, 'Remanded for resentencing.'); notice('Remanded', 'The case returns to the trial court.'); }
      else notice('Affirmed', 'The conviction and sentence stand.');
      postSentence();
    };
    show('APPEAL', h, hub, handlers);
  };

